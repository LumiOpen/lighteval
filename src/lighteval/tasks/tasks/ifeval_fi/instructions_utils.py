# Finnish-specific sentence splitting patterns
_ALPHABETS = "([A-Za-zÄÖÅäöå])"
_PREFIXES = "(Herra|St|Rouva|Neiti|Dr)[.]"
_SUFFIXES = "(Inc|Ltd|Jr|Sr|Co|Oy)"
_STARTERS = r"(Herra|Rouva|Neiti|Tohtori|Prof|Kapteeni|Kpt|Luutn|Hän\s|Se\s|He\s|Heidän\s|Meidän\s|Me\s|Mutta\s|Kuitenkin\s|Tämä\s|Missä tahansa)"
_ACRONYMS = "([A-Z][.][A-Z][.](?:[A-Z][.])?)"
_WEBSITES = "[.](com|net|org|io|gov|edu|me|fi|eu)"
_DIGITS = "([0-9])"
_MULTIPLE_DOTS = r"\.{2,}"


def split_into_sentences(text):
    """Split the text into sentences.

    Args:
        text: A string that consists of more than or equal to one sentences.

    Returns:
        A list of strings where each string is a sentence.
    """
    text = " " + text + " "
    text = text.replace("\n", " ")
    text = re.sub(_PREFIXES, "\\1 ", text)
    text = re.sub(_WEBSITES, " \\1", text)
    text = re.sub(_DIGITS + "[.]" + _DIGITS, "\\1 \\2", text)
    text = re.sub(
        _MULTIPLE_DOTS,
        lambda match: " " * len(match.group(0)) + " ",
        text,
    )
    if "Ph.D" in text:
        text = text.replace("Ph.D.", "Ph D ")
    text = re.sub(r"\s" + _ALPHABETS + "[.] ", " \\1 ", text)
    text = re.sub(_ACRONYMS + " " + _STARTERS, "\\1 \\2", text)
    text = re.sub(
        _ALPHABETS + "[.]" + _ALPHABETS + "[.]" + _ALPHABETS + "[.]",
        "\\1 \\2 \\3 ",
        text,
    )
    text = re.sub(_ALPHABETS + "[.]" + _ALPHABETS + "[.]", "\\1 \\2 ", text)
    text = re.sub(" " + _SUFFIXES + "[.] " + _STARTERS, " \\1 \\2", text)
    text = re.sub(" " + _SUFFIXES + "[.]", " \\1 ", text)
    text = re.sub(" " + _ALPHABETS + "[.]", " \\1 ", text)
    if "\u201c" in text:
        text = text.replace(".\u201c", "\u201c.")
    if '"' in text:
        text = text.replace('."', '".')
    if "!" in text:
        text = text.replace('!"', '"!')
    if "?" in text:
        text = text.replace('?"', '"?')
    text = text.replace(".", ". ")
    text = text.replace("?", "? ")
    text = text.replace("!", "! ")
    text = text.replace(" ", ".")
    sentences = text.split(" ")
    sentences = [s.strip() for s in sentences]
    if sentences and not sentences[-1]:
        sentences = sentences[:-1]
    return sentences


def count_words(text):
    """Counts the number of words."""
    tokenizer = nltk.tokenize.RegexpTokenizer(r"\w+")
    tokens = tokenizer.tokenize(text)
    num_words = len(tokens)
    return num_words


@functools.lru_cache(maxsize=None)
def _get_sentence_tokenizer():
    return nltk.data.load("nltk:tokenizers/punkt/finnish.pickle")


def count_sentences(text):
    """Count the number of sentences."""
    tokenizer = _get_sentence_tokenizer()
    tokenized_sentences = tokenizer.tokenize(text)
    return len(tokenized_sentences)


